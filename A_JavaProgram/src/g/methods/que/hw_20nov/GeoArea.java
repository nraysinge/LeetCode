package g.methods.que.hw_20nov;

public class GeoArea {

		public void areaOfCircle(double r) {
			double area=3.14*r*r;
			System.out.println("Area of circule:- "+area);
		}
		public void areaOfRectangle(int l, int b) {
			int a=l*b;
			System.out.println("Area of Rectangule:- "+a);
		}
		public void areaOfSquare(int a) {
				int c=a*a;
				System.out.println("Area OF Square is:- "+c);
		}			
		public void circumferenceOfCircle(double r) {
				double circum=3.14*2*r;
				System.out.println("Circumference Of Circle:- "+circum);
		}
			
	}

