package g.methods.que.hw_20nov;

public class sub_method1 {
	public void total(int a, int b) {
		int c=a+b;
		System.out.println("result is:- "+c);
	}

	public void subtraction(int d, int e) {
		int f=d-e;
		System.out.println("result is:- "+f);
	}
	
	public void multiplication(int g, int h) {
		int i=g*h;
		System.out.println("result is:- "+i);
	}
	
	public void division(int k, int l) {
		int m=k/l;
		System.out.println("result is:- "+m);
	}
}
