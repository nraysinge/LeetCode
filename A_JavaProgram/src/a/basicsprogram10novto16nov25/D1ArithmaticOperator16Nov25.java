package a.basicsprogram10novto16nov25;

public class D1ArithmaticOperator16Nov25 {
	public static void main(String[] args) {
		double a=100;
		System.out.println(a);
		
		double b=200;
		System.out.println(b);
		
		double c=a+b;
		System.out.println(c);
		
		c=b-a;
		System.out.println(c);
		
		c=a*b;
		System.out.println(c);
		
		c=a/b;
		System.out.println(c);
		
		c=a%b;
		System.out.println(c);
		
		
	}

}
